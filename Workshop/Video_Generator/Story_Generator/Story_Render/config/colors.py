# 🎨 ASS (Advanced SubStation Alpha) में रंगों का फॉर्मेट '&HAABBGGRR&' होता है
# यहाँ हमने Blue, Green, Red के कॉम्बिनेशन से प्रीमियम रंग बनाए हैं।

PREMIUM_COLORS = [
    "&H00D7FF&",  # 1. Gold (गोल्डन)
    "&HFFFF00&",  # 2. Cyan (आसमानी)
    "&H507FFF&",  # 3. Coral (नारंगी-गुलाबी)
    "&H90EE90&",  # 4. Light Green (हल्का हरा)
    "&HD670DA&",  # 5. Orchid (बैंगनी)
    "&HEBCE87&",  # 6. Sky Blue (हल्का नीला)
    "&H00FFFF&",  # 7. Yellow (पीला)
    "&H00A5FF&",  # 8. Orange (संतरी)
    "&HCBC0FF&",  # 9. Pink (गुलाबी)
    "&HD0E040&",  # 10. Turquoise (फिरोज़ी)
    "&HFF00FF&",  # 11. Magenta (चमकीला गुलाबी)
    "&H00FF00&",  # 12. Lime Green (नींबू हरा)
]

# ══════════════════════════════════════════════════════════════════════════════
# 🛠️ HELPER FUNCTION: रंगों को लगाने के लिए टैग बनाना
# ══════════════════════════════════════════════════════════════════════════════
def get_color_tag(index):
    """
    यह फंक्शन इंडेक्स (0, 1, 2...) के हिसाब से रंग लौटाता है।
    अगर इंडेक्स बढ़ जाए, तो यह वापस शुरुआत से रंग देता है।
    """
    color = PREMIUM_COLORS[index % len(PREMIUM_COLORS)]
    return color
